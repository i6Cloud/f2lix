class Movie {
  final String title;
  final String genre;
  final String poster;
  final String backdrop;
  final String description;
  final String category;
  final double rating;
  final int year;

  const Movie({
    required this.title,
    required this.genre,
    required this.poster,
    required this.backdrop,
    required this.description,
    required this.category,
    required this.rating,
    required this.year,
  });
}
